def seed(log_fn):
    """Seed products from backup."""
    count = 0
    for product in DEFAULT_PRODUCTS:
        try:
            product_id = ObjectId(product["_id"])
            existing = products_collection.find_one({"_id": product_id})

            if existing:
                log_fn(f"Product '{product.get('name')}' already exists — skipping")
            else:
                doc = {
                    "_id": product_id,
                    "name": product.get("name"),
                    "description": product.get("description"),
                    "category_id": product.get("category_id"),
                    "price": product.get("price"),
                    "sku": product.get("sku"),
                    "inventory_prerequisite": product.get("inventory_prerequisite", False),
                    "no_price": product.get("no_price", False),
                    "transaction_count": product.get("transaction_count", 0),
                    "created_by": product.get("created_by"),
                    "created_at": datetime.datetime.utcnow(),
                }
                products_collection.insert_one(doc)
                count += 1
                if count % 50 == 0:
                    log_fn(f"  ... imported {count} products")
        except Exception as e:
            log_fn(f"Error importing product '{product.get('name')}': {e}")

    log_fn(f"Imported {count} products")
